"""Build the store's text from WANDS, the Wayfair ANnotation DataSet, at a pinned commit.

    python prep/wands_text.py [--source DIR]

Reads product.csv from WANDS (MIT licence) at the commit below, downloading it unless --source points at a local copy
of the dataset folder (with LICENSE in its parent), and writes examples/data/wands-text/: products.csv.gz, WANDS's own
LICENSE, and README.md, the data card. The same commit and seed always give the same files.

How the text is prepared:
- every product with a name, except those whose name or description names the store or its own brands (the book
  doesn't name the store, and a model trained on its name would write it); WANDS's text is already lowercased, with
  spaces around punctuation
- descriptions are cut at the last sentence end within 600 characters, or at a word boundary when there is none,
  to keep the file small; a product without a description keeps an empty one
- each product is in one split, chosen with a fixed seed: 80% train, 10% validation and 10% test, so text the
  models are scored on never appears in what they learned from
"""
from __future__ import annotations

import argparse
import urllib.request
from pathlib import Path

import numpy as np
import pandas as pd

WANDS_REPO = "https://github.com/wayfair/WANDS"
WANDS_COMMIT = "3b74dcf4ba29ab8ff3e6a50b5b09fc627cb882b5"
RAW = f"https://raw.githubusercontent.com/wayfair/WANDS/{WANDS_COMMIT}/{{path}}"
SEED = 2026
SPLITS = (("train", 0.8), ("validation", 0.1), ("test", 0.1))
DESCRIPTION_CHARS = 600
STORE = r"\bwayfair\b"                         # the store's name, which also leads its own brands' names
OUT = Path(__file__).resolve().parent.parent / "examples" / "data" / "wands-text"


def fetch(path: str, source: Path | None) -> bytes:
    if source is None:
        with urllib.request.urlopen(RAW.format(path=path), timeout=120) as r:
            return r.read()
    return (source.parent / path).read_bytes()


def cut(text: object) -> str:
    text = " ".join(str(text).split()) if isinstance(text, str) else ""
    if len(text) <= DESCRIPTION_CHARS:
        return text
    head = text[:DESCRIPTION_CHARS]
    end = head.rfind(" . ")
    return head[:end + 2] if end > 0 else head.rsplit(" ", 1)[0]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, help="a local copy of WANDS's dataset folder, with LICENSE in its parent")
    args = ap.parse_args()
    import io
    raw = pd.read_csv(io.BytesIO(fetch("dataset/product.csv", args.source)), sep="\t")
    raw = raw[raw.product_name.notna()].sort_values("product_id")
    names_store = raw.product_name.str.contains(STORE) | raw.product_description.fillna("").str.contains(STORE)
    dropped, raw = int(names_store.sum()), raw[~names_store]
    order = np.random.default_rng(SEED).permutation(len(raw))
    bounds = np.cumsum([int(round(share * len(raw))) for _, share in SPLITS])[:-1]
    split = np.empty(len(raw), dtype=object)
    for (name, _), part in zip(SPLITS, np.split(order, bounds)):
        split[part] = name
    out = pd.DataFrame({"product_id": raw.product_id.to_numpy(), "split": split,
                        "name": [" ".join(n.split()) for n in raw.product_name],
                        "product_class": raw.product_class.fillna("").to_numpy(),
                        "description": [cut(d) for d in raw.product_description]})

    OUT.mkdir(parents=True, exist_ok=True)
    out.to_csv(OUT / "products.csv.gz", index=False, compression={"method": "gzip", "mtime": 0})
    licence = fetch("LICENSE", args.source).decode("utf-8")
    (OUT / "LICENSE").write_text(licence, encoding="utf-8")
    notice = next(line.strip() for line in licence.splitlines() if line.startswith("Copyright"))
    counts = out.split.value_counts()
    words = out.name.str.split().str.len().sum() + out.description.str.split().str.len().sum()
    (OUT / "README.md").write_text(f"""# The store's text

The text every example in this book learns from: the product names, classes and descriptions of WANDS, the Wayfair
ANnotation DataSet, a public product-search dataset. Generated by `prep/wands_text.py`; never edit these files by hand.

**Source:** {WANDS_REPO}, commit `{WANDS_COMMIT}`.
**Licence:** MIT, {notice}. See [`LICENSE`](LICENSE), copied from the source repository.
**Paper:** Chen, Y., Liu, S., Liu, Z., Sun, W., Baltrunas, L. and Schroeder, B. (2022). WANDS: Dataset for
Product Search Relevance Assessment. ECIR 2022.

| File | Rows | What |
| --- | --- | --- |
| `products.csv.gz` | {len(out):,} | `product_id`, `split`, `name`, `product_class`, `description` |

Splits (seed {SEED}): {counts.get('train', 0):,} train, {counts.get('validation', 0):,} validation and {counts.get('test', 0):,} test
products; each product is in one. About {words:,} words of names and descriptions in all.

**Prepared:** WANDS's text is already lowercased, with spaces around punctuation. {dropped} products whose name or
description names the store or its own brands are left out, so no model in the book learns to write the store's name.
Descriptions are cut at the last sentence end within {DESCRIPTION_CHARS} characters, or at a word boundary when there is
none.
""", encoding="utf-8")
    print(f"products: {len(out):,} ({counts.get('train', 0):,} train)  words: {words:,}  "
          f"size: {(OUT / 'products.csv.gz').stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
