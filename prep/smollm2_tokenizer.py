"""Fetch an open model's tokenizer, so chapter 2 can tokenize offline: SmolLM2's, at a pinned revision.

    python prep/smollm2_tokenizer.py

Writes examples/data/smollm2-tokenizer/: tokenizer.json as the model's repository publishes it, the Apache License 2.0
the model card names, and README.md, the data card. The same revision always gives the same files.
"""
import json
import urllib.request
from pathlib import Path

MODEL = "HuggingFaceTB/SmolLM2-360M"
REVISION = "f8027fd0eaeea54caa13c31d31b9fdc459c38b49"
FILE = f"https://huggingface.co/{MODEL}/resolve/{REVISION}/{{name}}"
LICENCE = "https://www.apache.org/licenses/LICENSE-2.0.txt"
OUT = Path(__file__).resolve().parent.parent / "examples" / "data" / "smollm2-tokenizer"


def get(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as r:
        return r.read()


def main() -> None:
    card = json.loads(get(f"https://huggingface.co/api/models/{MODEL}/revision/{REVISION}"))
    licence = card.get("cardData", {}).get("license")
    if licence != "apache-2.0":
        raise SystemExit(f"{MODEL} at {REVISION[:8]} is licensed {licence!r}, not apache-2.0: check before using it")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tokenizer.json").write_bytes(get(FILE.format(name="tokenizer.json")))
    (OUT / "LICENSE").write_bytes(get(LICENCE))
    vocab = len(json.loads((OUT / "tokenizer.json").read_text())["model"]["vocab"])
    (OUT / "README.md").write_text(f"""# SmolLM2's tokenizer

The tokenizer of SmolLM2, an open language model by Hugging Face, used by chapter 2 to compare the tokenizer the book
builds with one an open model uses. Generated by `prep/smollm2_tokenizer.py`; never edit these files by hand.

**Source:** https://huggingface.co/{MODEL}, revision `{REVISION}`.
**Licence:** Apache License 2.0, as the model card states. See [`LICENSE`](LICENSE).

| File | What |
| --- | --- |
| `tokenizer.json` | The tokenizer as the model's repository publishes it: {vocab:,} tokens, their merges and how text is split first |
""", encoding="utf-8")
    print(f"tokenizer: {vocab:,} tokens")


if __name__ == "__main__":
    main()
